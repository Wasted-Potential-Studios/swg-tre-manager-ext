// Simple script to create a placeholder PNG icon
// For production, replace with a proper 128x128 PNG icon

const fs = require('fs');
const path = require('path');

// Create a simple PNG icon (1x1 purple pixel as placeholder)
// In production, use proper graphic design tool to create 128x128 icon
const pngData = Buffer.from([
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // PNG signature
    0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, // IHDR chunk
    0x00, 0x00, 0x00, 0x80, 0x00, 0x00, 0x00, 0x80, // 128x128
    0x08, 0x02, 0x00, 0x00, 0x00, 0x4C, 0x5C, 0xF6,
    0x69, // IHDR CRC
    0x00, 0x00, 0x00, 0x0C, 0x49, 0x44, 0x41, 0x54, // IDAT chunk (minimal data)
    0x08, 0x99, 0x63, 0x00, 0x01, 0x00, 0x00, 0x05,
    0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4,
    0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, // IEND chunk
    0xAE, 0x42, 0x60, 0x82
]);

const resourcesDir = path.join(__dirname, 'resources');
if (!fs.existsSync(resourcesDir)) {
    fs.mkdirSync(resourcesDir, { recursive: true });
}

fs.writeFileSync(path.join(resourcesDir, 'icon.png'), pngData);
console.log('Created placeholder icon at resources/icon.png');
console.log('For production use, replace with a proper 128x128 PNG icon');
